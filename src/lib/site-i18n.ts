export function wxLabel(code: number | null | undefined, lang: Lang) {
  const row = code != null ? WX[code] : undefined;
  if (!row) return lang === "ru" ? "Нет данных" : lang === "en" ? "No data" : "Ma'lumot yo'q";
  return row[lang === "uz" ? 0 : lang === "ru" ? 1 : 2];
}

export type Condition = "clear" | "partly" | "cloudy" | "fog" | "drizzle" | "rain" | "snow" | "thunder";

export function wxCondition(code: number | null | undefined): Condition {
  if (code == null) return "cloudy";
  if (code <= 1) return "clear";
  if (code === 2) return "partly";
  if (code === 3) return "cloudy";
  if (code === 45 || code === 48) return "fog";
  if (code >= 51 && code <= 57) return "drizzle";
  if ((code >= 61 && code <= 67) || (code >= 80 && code <= 82)) return "rain";
  if ((code >= 71 && code <= 77) || code === 85 || code === 86) return "snow";
  return "thunder";
}

